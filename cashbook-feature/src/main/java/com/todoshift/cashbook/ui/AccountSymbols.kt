@androidx.compose.runtime.NonSkippableComposable @Composable internal fun AccountSymbol(value:String,modifier:Modifier=Modifier,color:Color=MaterialTheme.colorScheme.primary) {
 val resource=SymbolDrawables[value]
 if(resource!=null) Icon(painterResource(resource),AccountIconCatalog.find(value)?.let{if(CashBookText.arabic())it.keywords.substringBefore(' ')else it.name.replace('-',' ')},modifier.size(24.dp),tint=color)
 else if(value.isNotBlank()&&!value.startsWith("i:")) Text(value,modifier,fontSize=22.sp)
 else Icon(painterResource(R.drawable.aci_001),tr(R.string.cb_146),modifier.size(24.dp),tint=color)
}
